ZH_ONLY = ["怎麼", "這座", "這個", "預測點", "番茄鐘", "咒語書", "航海圖", "紀錄", "複習", "通關", "抽問", "講解", "還沒", "請", "們", "會", "與", "對", "說"]


def main() -> None:
    if len(JA) != len(build_en.PAIRS):
        sys.exit(f"JA 有 {len(JA)} 項，build_en.PAIRS 有 {len(build_en.PAIRS)} 項，要一一對應")
    pairs = [(zh, en if ja is None else ja) for (zh, en), ja in zip(build_en.PAIRS, JA)]
    html = build_en.translate(pairs)
    html = langs.apply(html, "ja/")
    bad = []
    for i, line in enumerate(html.splitlines(), 1):
        if "<!--LANG-->" in line or "課程設計.md" in line:
            continue
        hits = [w for w in ZH_ONLY if w in line]
        if hits:
            bad.append(f"{i}: {hits} {line.strip()[:100]}")
    if bad:
        sys.exit("疑似沒翻到的中文：\n" + "\n".join(bad))
    OUT.mkdir(exist_ok=True)
    (OUT / "index.html").write_text(html, encoding="utf-8")
    print("已產生 ja/index.html")


if __name__ == "__main__":
    main()
